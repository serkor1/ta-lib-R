//! testthat file generation
//!
//! Renders one testthat file per indicator, written to
//! 'tests/testthat/test-ta_<ALIAS>.R' by main() and overwritten on
//! every run (no protected regions). What a file contains follows
//! from the metadata:
//!
//!   - rolling statistics (GroupId 'Statistic Functions'): a short
//!     fast-track file (',y=SPY[,2]' appended for the bivariate
//!     BETA/CORREL)
//!   - chartable indicators: .plotly/.ggplot method tests, including
//!     candlesticks and moving averages whose chart methods render
//!     from their own templates
//!   - univariate indicators (a single input series): a .numeric
//!     method test

