/// Render the testthat file of an indicator
pub fn render_test(f: &MetaData) -> String {
    let fun = function_name(&f.indicator);

    // rolling statistics fast-track: a short univariate file,
    // with the second input series of BETA/CORREL passed as 'y'
    if f.family == "Statistic Functions" || f.family == "Math Operators" {
        let additional = if f.input.len() > 1 { ",y=SPY[,2]" } else { "" };

        return format!(
            "{HEADER}{}",
            ROLLING_TESTS
                .replace("${FUN}", fun)
                .replace("${ADDITIONAL}", additional)
        );
    }

    // passthrough inputs (MAVP: periods) are required formals, so
    // every call site supplies a deterministic full-length vector
    // matched to its dataset via the ${PASS_<DATA>} placeholders
    let pass = |data: &str| {
        f.passthrough
            .iter()
            .map(|p| format!(", {p} = rep(5, nrow({data}))"))
            .collect::<String>()
    };

    // the camelCase alias; single-word indicator names camelCase
    // to themselves, dropping the '#camel#' test lines instead
    let camel = camel_case_name(&f.indicator);
    let has_camel = camel != fun;

    let fill = |template: &str| {
        render_camel(template, has_camel)
            .replace("${FUN}", fun)
            .replace("${ALIAS}", &f.indicator)
            .replace("${CAMEL}", &camel)
            .replace("${FORMULA}", &f.default_formula())
            .replace("${PASS_SPY}", &pass("SPY"))
            .replace("${PASS_BTC}", &pass("BTC"))
            .replace("${PASS_ATOM}", &pass("ATOM"))
    };

    let mut out = format!("{HEADER}{}", fill(STANDARD_TESTS));

    // chartable indicators: candlesticks and moving averages carry
    // their chart methods regardless of CHART_TYPES
    let chartable = chart_type(&f.indicator).is_some()
        || is_candlestick(&f.indicator)
        || ma_type(&f.indicator).is_some();

    if chartable {
        out.push_str(&fill(PLOTLY_TESTS));
        out.push_str(&fill(GGPLOT_TESTS));
    }

    // univariate indicators carry a .numeric method
    if f.input.len() == 1 {
        out.push_str(&fill(NUMERIC_TESTS));
    }

    out
}

#[cfg(test)]
mod tests {
    use super::*;

    fn meta(indicator: &str, family: &str, input: &[&str]) -> MetaData {
        MetaData {
            indicator: indicator.to_string(),
            family: family.to_string(),
            input: input.iter().map(|s| s.to_string()).collect(),
            ..Default::default()
        }
    }

    #[test]
    fn renders_standard_chartable_test() {
        let rendered = render_test(&meta("BBANDS", "Overlap Studies", &["close"]));

        assert!(rendered.contains("output <- bollinger_bands(SPY)"));
        assert!(rendered.contains("alias  <- BBANDS(SPY)"));
        assert!(rendered.contains("camel <- bollingerBands(SPY)"));
        assert!(rendered.contains("object = bollingerBands_lookback,"));
        assert!(!rendered.contains("#camel#"), "unstripped camel prefix");
        assert!(rendered.contains("cols = ~close"));
        assert!(rendered.contains("<plotly>-methods for <data.frame>"));
        assert!(rendered.contains("<ggplot>-methods for <matrix>"));
        assert!(rendered.contains("<numeric> methods"));
        assert!(!rendered.contains("${"), "unreplaced placeholder");
    }

    #[test]
    fn renders_candlestick_test_without_numeric() {
        let rendered = render_test(&meta(
            "CDLDOJI",
            "Pattern Recognition",
            &["open", "high", "low", "close"],
        ));

        assert!(rendered.contains("cols = ~open + high + low + close"));
        assert!(rendered.contains("<plotly>-methods for <data.frame>"));
        assert!(!rendered.contains("<numeric> methods"));

        // 'doji' camelCases to itself:
        // the camel test lines are dropped
        assert!(!rendered.contains("camel <-"));
        assert!(!rendered.contains("#camel#"), "unstripped camel prefix");
    }

    #[test]
    fn renders_passthrough_args() {
        let mut m = meta("MAVP", "Overlap Studies", &["close"]);
        m.passthrough.push("periods".to_string());

        let rendered = render_test(&m);

        // every call site supplies a full-length periods vector
        // matched to its dataset
        assert!(
            rendered.contains("variable_moving_average_period(SPY, periods = rep(5, nrow(SPY)))")
        );
        assert!(rendered.contains("cols = ~close, periods = rep(5, nrow(BTC))"));
        assert!(
            rendered
                .contains("indicator(variable_moving_average_period, periods = rep(5, nrow(BTC)))")
        );
        assert!(
            rendered
                .contains("variable_moving_average_period(BTC[[1]], periods = rep(5, nrow(BTC)))")
        );
        assert!(!rendered.contains("${"), "unreplaced placeholder");
    }

    #[test]
    fn renders_rolling_tests() {
        let rendered = render_test(&meta("STDDEV", "Statistic Functions", &["close"]));

        assert!(rendered.contains("Runs without *any* conditions"));
        assert!(rendered.contains("x = SPY[,1]\n"));
        assert!(!rendered.contains("y=SPY[,2]"));
        assert!(!rendered.contains("Alias and function similarity"));

        // the bivariate rolling statistics pass
        // the second column as 'y'
        let rendered = render_test(&meta("BETA", "Statistic Functions", &["close", "close"]));
        assert!(rendered.contains("x = SPY[,1],y=SPY[,2]"));
    }
}
